export function translateBadge(badge, lang = 'en') {
  if (!badge) return badge;
  if ((lang === 'km' || lang === 'kh') && BADGE_TRANSLATIONS_KM[badge]) {
    return BADGE_TRANSLATIONS_KM[badge];
  }
  return badge;
}

export function translateOrderStatusLabel(status, lang = 'en') {
  if (!status) return status;
  if (lang === 'km' || lang === 'kh') {
    if (ORDER_STATUS_TRANSLATIONS_KM[status]) return ORDER_STATUS_TRANSLATIONS_KM[status];
    const norm = String(status).toLowerCase().replace(/\s+/g, '_');
    if (ORDER_STATUS_TRANSLATIONS_KM[norm]) return ORDER_STATUS_TRANSLATIONS_KM[norm];
  }
  return status;
}

export function translateProductField(product, field, lang = 'en') {
  if (!product) return '';
  const val = product[field] || '';
  if ((lang === 'km' || lang === 'kh') && product.id && PRODUCT_TRANSLATIONS_KM[product.id]) {
    const tr = PRODUCT_TRANSLATIONS_KM[product.id][field];
    if (tr) return tr;
  }
  return val;
}

